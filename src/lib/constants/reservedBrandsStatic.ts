/**
 * 정적 카테고리(변경 없는 고정 블랙리스트)를 서버 메모리에서 즉시 확인
 * DB 조회 없이 수 μs 내 결과 반환
 */
export function checkStaticReservedBrand(brandId: string): StaticBrandCheckResult {
  const id = brandId.toLowerCase().trim();

  if (SYSTEM_SET.has(id)) return { blocked: true, category: 'SYSTEM', message: CATEGORY_MESSAGES.SYSTEM };
  if (ABUSE_SET.has(id)) return { blocked: true, category: 'ABUSE', message: CATEGORY_MESSAGES.ABUSE };
  if (ADULT_GAMBLING_SET.has(id)) return { blocked: true, category: 'ADULT_GAMBLING', message: CATEGORY_MESSAGES.ADULT_GAMBLING };
  if (RELIGION_POLITICS_SET.has(id)) return { blocked: true, category: 'RELIGION_POLITICS', message: CATEGORY_MESSAGES.RELIGION_POLITICS };
  if (MILITARY_SECURITY_SET.has(id)) return { blocked: true, category: 'MILITARY_SECURITY', message: CATEGORY_MESSAGES.MILITARY_SECURITY };
  if (GEOGRAPHY_SET.has(id)) return { blocked: true, category: 'GEOGRAPHY', message: CATEGORY_MESSAGES.GEOGRAPHY };

  return { blocked: false };
}

